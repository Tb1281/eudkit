//! `.epmap` writer: pure-function port of the `SaveMap` trace-file tail
//! (`src/eudkit/maprw/savemap.py`) plus the `tracecrypt.mix` id scrambler
//! (`src/eudkit/core/eudfunc/trace/tracecrypt.py`).
//!
//! An `.epmap` file is what `epTrace.exe` opens to show `파일|함수|라인`
//! (file|function|line) stack traces for a debug build.
//!
//! ## Why byte parity with the Python writer is impossible by design
//!
//! Three independent randomness sources feed every Python `.epmap`, so two
//! Python builds of the *same* source never produce byte-identical files
//! either:
//!
//! 1. `H0` — `os.urandom(16)` evaluated once at `tracetool` import time
//!    (`i_header`; also embedded in the payload as the epTrace magic
//!    blob that the tool scans for).
//! 2. `H1` — `os.urandom(16)` regenerated on every `SaveMap`
//!    (`_reset_trace_map`).
//! 3. Trace entry ids — `tracecrypt.mix(_trace_key, _next_trace_id)`
//!    with `_trace_key = b2i4(os.urandom(4))` per `SaveMap`.
//!
//! The parity bar is therefore *format + semantic* parity, not byte
//! parity: `epTrace.exe` must open the file and resolve the
//! `file|function|line` entries. This module takes every nondeterministic
//! input explicitly (`h0`, `h1`, entry ids), so the determinism policy is
//! the caller's choice (the `eudc --epmap` default is seeded-deterministic;
//! `--epmap-random-headers` restores faithful-upstream randomness).
//!
//! File format (exact, mirroring the `savemap.py` tail):
//! ```text
//! H0: <32 lowercase hex chars>\n
//! H1: <32 lowercase hex chars>\n
//!  - <8 uppercase hex digits> : <file|func|line>\n   (one line per entry)
//! ```
//! The file is UTF-8 text (Python opens it with `encoding="utf-8"`).

/// `tracecrypt.T`: 4-round quadratic-residue-style scrambler over `u32`.
///
/// Faithful port of `tracecrypt.py::T`:
/// `x = (x * (xsq * (xsq * xsq + 1) + 1) + 0x8ADA4053) & 0xFFFFFFFF`
/// with `xsq = x*x`. Python ints are unbounded, but every operation is `+`
/// or `×`, so reducing mod 2³² at each step (wrapping arithmetic) yields
/// exactly the same low 32 bits as masking once at the end of the round.
fn t(mut x: u32) -> u32 {
    for _ in 0..4 {
        let xsq = x.wrapping_mul(x);
        let inner = xsq.wrapping_mul(xsq).wrapping_add(1);
        let mid = xsq.wrapping_mul(inner).wrapping_add(1);
        x = x.wrapping_mul(mid).wrapping_add(0x8ADA4053);
    }
    x
}

/// `tracecrypt.mix(x, y)`: trace-entry id scrambler.
///
/// `mix(x, y) = T(T(x) + y + 0x10F874F3) & 0xFFFFFFFF`. `T` masks its input
/// to 32 bits on entry, so the unbounded Python `T(x) + y + 0x10F874F3` is
/// exactly `wrapping_add` here.
pub fn mix(x: u32, y: u32) -> u32 {
    t(t(x).wrapping_add(y).wrapping_add(0x10F874F3))
}

/// Render an `.epmap` document over explicit inputs.
///
/// `h0`/`h1` are the two 16-byte headers; `entries` are
/// `(trace id, "file|function|line")` pairs in emission order. Pure: the
/// same inputs always produce the same bytes.
pub fn write_epmap(h0: &[u8; 16], h1: &[u8; 16], entries: &[(u32, &str)]) -> String {
    fn hex16(bytes: &[u8; 16]) -> String {
        const HEX: &[u8; 16] = b"0123456789abcdef";
        let mut s = String::with_capacity(32);
        for &b in bytes {
            s.push(HEX[(b >> 4) as usize] as char);
            s.push(HEX[(b & 0xF) as usize] as char);
        }
        s
    }
    let mut out = String::new();
    out.push_str("H0: ");
    out.push_str(&hex16(h0));
    out.push('\n');
    out.push_str("H1: ");
    out.push_str(&hex16(h1));
    out.push('\n');
    for (k, v) in entries {
        // Mirrors `f" - {k:08X} : {v}\n"` exactly: leading space, dash,
        // space, 8-digit UPPERCASE hex, space, colon, space.
        out.push_str(&format!(" - {k:08X} : {v}\n"));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mix_matches_python_vectors() {
        // Generated from the real `tracecrypt.py` (2026-10-18).
        let cases: &[(u32, u32, u32)] = &[
            (0x0, 0x0, 0x21427c13),
            (0x1, 0x0, 0x03372c24),
            (0xffff_ffff, 0xffff_ffff, 0x2b60eee1),
            (0x12345678, 0x9abc_def0, 0xd824f87b),
            (0x2a, 0x7, 0x04b4_3e4d4),
        ];
        for &(x, y, want) in cases {
            assert_eq!(mix(x, y), want, "mix({x:#x}, {y:#x})");
        }
    }

    #[test]
    fn write_epmap_matches_python_fixture() {
        // Fixture generated by the *real* Python writer expressions (the
        // `savemap.py::SaveMap` tail f-strings plus the real
        // `tracecrypt.mix` for entry ids) with fixed header bytes standing
        // in for the `os.urandom` calls. Inputs are pinned in the sidecar
        // JSON; the assertion is an exact string match — any format drift
        // fails here, loudly.
        let dir = format!("{}/tests/fixtures", env!("CARGO_MANIFEST_DIR"));
        let inputs: serde_json::Value = serde_json::from_str(
            &std::fs::read_to_string(format!("{dir}/epmap_py_fixture.inputs.json"))
                .expect("read inputs sidecar"),
        )
        .expect("parse inputs sidecar");
        fn hex16(s: &str) -> [u8; 16] {
            let b = (0..16)
                .map(|i| u8::from_str_radix(&s[2 * i..2 * i + 2], 16).unwrap())
                .collect::<Vec<_>>();
            b.try_into().unwrap()
        }
        let h0 = hex16(inputs["h0"].as_str().unwrap());
        let h1 = hex16(inputs["h1"].as_str().unwrap());
        let entries: Vec<(u32, String)> = inputs["entries"]
            .as_array()
            .unwrap()
            .iter()
            .map(|e| {
                (
                    e[0].as_u64().unwrap() as u32,
                    e[1].as_str().unwrap().to_string(),
                )
            })
            .collect();
        let refs: Vec<(u32, &str)> = entries.iter().map(|(k, v)| (*k, v.as_str())).collect();
        let got = write_epmap(&h0, &h1, &refs);
        let want = std::fs::read_to_string(format!("{dir}/epmap_py_fixture.epmap"))
            .expect("read epmap fixture");
        assert_eq!(got, want, "epmap output diverged from the Python writer");
    }

    #[test]
    fn write_epmap_empty_entries_is_headers_only() {
        let out = write_epmap(&[0u8; 16], &[0xffu8; 16], &[]);
        assert_eq!(
            out,
            "H0: 00000000000000000000000000000000\n\
             H1: ffffffffffffffffffffffffffffffff\n"
        );
    }
}
